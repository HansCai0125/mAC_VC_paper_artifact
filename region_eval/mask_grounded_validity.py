def rasterize_coco_polygon(annotation: dict, image: dict) -> PackedForegroundMask:
    """Rasterize one polygon annotation in a tight local crop with OpenCV."""
    segmentation = annotation.get("segmentation")
    if not isinstance(segmentation, list) or not segmentation:
        raise ValueError(f"annotation {annotation.get('id')} is not polygon encoded")
    polygons = []
    all_x, all_y = [], []
    for flat in segmentation:
        if not isinstance(flat, list) or len(flat) < 6 or len(flat) % 2:
            raise ValueError(f"invalid polygon for annotation {annotation.get('id')}")
        coordinates = np.asarray(flat, dtype=np.float64).reshape(-1, 2)
        polygons.append(coordinates)
        all_x.extend(coordinates[:, 0].tolist())
        all_y.extend(coordinates[:, 1].tolist())
    image_width = int(image["width"])
    image_height = int(image["height"])
    x0 = max(0, int(floor(min(all_x))))
    y0 = max(0, int(floor(min(all_y))))
    x1 = min(image_width, int(ceil(max(all_x))) + 1)
    y1 = min(image_height, int(ceil(max(all_y))) + 1)
    if x1 <= x0 or y1 <= y0:
        raise ValueError(f"degenerate polygon crop for annotation {annotation.get('id')}")
    local = np.zeros((y1 - y0, x1 - x0), dtype=np.uint8)
    contours = []
    for coordinates in polygons:
        shifted = coordinates - np.asarray([x0, y0], dtype=np.float64)
        contours.append(np.rint(shifted).astype(np.int32).reshape(-1, 1, 2))
    cv2.fillPoly(local, contours, color=1)
    foreground_area = int(np.count_nonzero(local))
    if foreground_area <= 0:
        raise ValueError(f"empty rasterized polygon for annotation {annotation.get('id')}")
    packed = np.packbits(local.reshape(-1), bitorder="big")
    return PackedForegroundMask(
        x0=x0,
        y0=y0,
        width=int(local.shape[1]),
        height=int(local.shape[0]),
        packed=packed,
        foreground_area=foreground_area,
        coco_area=float(annotation.get("area", foreground_area)),
    )


def _rectangle_intersects(first, second) -> bool:
    return (
        min(float(first[2]), float(second[2]))
        > max(float(first[0]), float(second[0]))
        and min(float(first[3]), float(second[3]))
        > max(float(first[1]), float(second[1]))
    )


def _local_prediction_slice(rectangle, mask: PackedForegroundMask):
    x1, y1, x2, y2 = map(float, rectangle)
    left = max(0, int(floor(x1)) - mask.x0)
    top = max(0, int(floor(y1)) - mask.y0)
    right = min(mask.width, int(ceil(x2)) - mask.x0)
    bottom = min(mask.height, int(ceil(y2)) - mask.y0)
    if right <= left or bottom <= top:
        return None
    return top, bottom, left, right


def _prediction_pixel_area(rectangle, image_width: int, image_height: int) -> int:
    x1, y1, x2, y2 = map(float, rectangle)
    left = max(0, int(floor(x1)))
    top = max(0, int(floor(y1)))
    right = min(image_width, int(ceil(x2)))
    bottom = min(image_height, int(ceil(y2)))
    return max(0, right - left) * max(0, bottom - top)


def foreground_metrics(
        mask_record: PackedForegroundMask,
        predictions: list[dict],
        *,
        image_width: int,
        image_height: int,
) -> dict:
    """Compute mask coverage, best single coverage, and collective gain."""
    foreground = mask_record.unpack()
    candidates = []
    for prediction in predictions:
        local_slice = _local_prediction_slice(prediction["xyxy"], mask_record)
        if local_slice is None:
            continue
        top, bottom, left, right = local_slice
        overlap_pixels = int(np.count_nonzero(foreground[top:bottom, left:right]))
        if overlap_pixels <= 0:
            continue
        pred_area = _prediction_pixel_area(
            prediction["xyxy"], image_width, image_height
        )
        denominator = mask_record.foreground_area + pred_area - overlap_pixels
        candidates.append({
            "id": str(prediction["id"]),
            "score": float(prediction.get("score", 0.0)),
            "slice": local_slice,
            "overlap_pixels": overlap_pixels,
            "mask_iou": overlap_pixels / denominator if denominator else 0.0,
            "foreground_precision": overlap_pixels / pred_area if pred_area else 0.0,
        })
    candidates.sort(
        key=lambda row: (-row["overlap_pixels"], -row["score"], row["id"])
    )
    covered_foreground = np.zeros_like(foreground, dtype=bool)
    marginal_ids = []
    marginal_pixels = []
    covered_count = 0
    for candidate in candidates:
        top, bottom, left, right = candidate["slice"]
        region = foreground[top:bottom, left:right]
        already = covered_foreground[top:bottom, left:right]
        new_pixels = int(np.count_nonzero(region & ~already))
        if new_pixels <= 0:
            continue
        already |= region
        covered_count += new_pixels
        marginal_ids.append(candidate["id"])
        marginal_pixels.append(new_pixels)
    foreground_area = mask_record.foreground_area
    mask_ac = min(1.0, covered_count / foreground_area)
    mask_best = (
        candidates[0]["overlap_pixels"] / foreground_area if candidates else 0.0
    )
    return {
        "MaskAC": mask_ac,
        "MaskBestCoverage": mask_best,
        "MaskCollectiveGain": max(0.0, mask_ac - mask_best),
        "MaskABO": max((row["mask_iou"] for row in candidates), default=0.0),
        "MaskBestPredPrecision": max(
            (row["foreground_precision"] for row in candidates), default=0.0
        ),
        "mask_intersecting_pred_count": len(candidates),
        "mask_marginal_contributor_count": len(marginal_ids),
        "mask_substantial_marginal_contributor_count": sum(
            pixels / foreground_area >= 0.01 for pixels in marginal_pixels
        ),
        "mask_marginal_pred_ids": ";".join(marginal_ids),
        "mask_best_pred_id": candidates[0]["id"] if candidates else "",
    }


def _pearson(first: np.ndarray, second: np.ndarray) -> float:
    if len(first) < 2 or np.std(first) <= EPSILON or np.std(second) <= EPSILON:
        return 0.0
    return float(np.corrcoef(first, second)[0, 1])


def _rankdata(values: np.ndarray) -> np.ndarray:
    order = np.argsort(values, kind="mergesort")
    ranks = np.empty(len(values), dtype=float)
    start = 0
    while start < len(values):
        end = start + 1
        while end < len(values) and values[order[end]] == values[order[start]]:
            end += 1
        ranks[order[start:end]] = 0.5 * (start + end - 1) + 1.0
        start = end
    return ranks


def _spearman(first: np.ndarray, second: np.ndarray) -> float:
    return _pearson(_rankdata(first), _rankdata(second))


def _fraction(mask: np.ndarray) -> float:
    return float(np.mean(mask)) if len(mask) else 0.0


def summarize_rows(rows: list[dict]) -> dict:
    box_ac = np.asarray([float(row["AC"]) for row in rows], dtype=float)
    mask_ac = np.asarray([float(row["MaskAC"]) for row in rows], dtype=float)
    box_gain = np.asarray(
        [float(row["CollectiveGain"]) for row in rows], dtype=float
    )
    mask_gain = np.asarray(
        [float(row["MaskCollectiveGain"]) for row in rows], dtype=float
    )
    vc = np.asarray([float(row["local_VC"]) for row in rows], dtype=float)
    box_positive = box_gain > GAIN_THRESHOLD
    mask_positive = mask_gain > GAIN_THRESHOLD
    both_positive = box_positive & mask_positive
    area_ratio = np.asarray(
        [float(row["raster_to_coco_area_ratio"]) for row in rows], dtype=float
    )
    return {
        "n_gt": len(rows),
        "box_AC_mean": float(np.mean(box_ac)),
        "mask_AC_mean": float(np.mean(mask_ac)),
        "box_minus_mask_AC_mean": float(np.mean(box_ac - mask_ac)),
        "AC_mask_MAE": float(np.mean(np.abs(box_ac - mask_ac))),
        "AC_mask_RMSE": float(np.sqrt(np.mean((box_ac - mask_ac) ** 2))),
        "r_boxAC_maskAC": _pearson(box_ac, mask_ac),
        "rho_boxAC_maskAC": _spearman(box_ac, mask_ac),
        "box_gain_mean": float(np.mean(box_gain)),
        "mask_gain_mean": float(np.mean(mask_gain)),
        "box_minus_mask_gain_mean": float(np.mean(box_gain - mask_gain)),
        "gain_mask_MAE": float(np.mean(np.abs(box_gain - mask_gain))),
        "r_boxGain_maskGain": _pearson(box_gain, mask_gain),
        "rho_boxGain_maskGain": _spearman(box_gain, mask_gain),
        "P_box_AC050_mask_below050": _fraction(
            (box_ac >= AC_THRESHOLD) & (mask_ac < AC_THRESHOLD)
        ),
        "P_mask_AC050_box_below050": _fraction(
            (mask_ac >= AC_THRESHOLD) & (box_ac < AC_THRESHOLD)
        ),
        "P_abs_AC_gap_gt010": _fraction(np.abs(box_ac - mask_ac) > 0.10),
        "P_box_gain_gt005": _fraction(box_positive),
        "P_mask_gain_gt005": _fraction(mask_positive),
        "P_both_gain_gt005": _fraction(both_positive),
        "P_box_gain_gt005_mask_not": _fraction(box_positive & ~mask_positive),
        "P_mask_gain_gt005_box_not": _fraction(mask_positive & ~box_positive),
        "P_mask_gain_gt005_given_box_gain_gt005": (
            _fraction(mask_positive[box_positive]) if np.any(box_positive) else 0.0
        ),
        "P_valid_collective": _fraction(both_positive & (vc >= 0.50)),
        "P_VC_below050_given_both_gain_gt005": (
            _fraction(vc[both_positive] < 0.50) if np.any(both_positive) else 0.0
        ),
        "raster_to_coco_area_ratio_mean": float(np.mean(area_ratio)),
        "raster_to_coco_area_ratio_p05": float(np.quantile(area_ratio, 0.05)),
        "raster_to_coco_area_ratio_p95": float(np.quantile(area_ratio, 0.95)),
    }


def _run_complete_matches(
        path: Path, source: CachedRun, annotation_sha256: str) -> bool:
    if not path.is_file():
        return False
    marker = _read_json(path)
    return (
        marker.get("status") == "complete"
        and marker.get("validity_version") == VALIDITY_VERSION
        and marker.get("source_run_fingerprint") == source.run_fingerprint
        and marker.get("annotation_sha256") == annotation_sha256
        and float(marker.get("theta", -1)) == PRIMARY_THETA
    )


def _evaluate_source(
        source: CachedRun,
        *,
        output_root: Path,
        natural_root: Path,
        annotation_sha256: str,
        images: dict[int, dict],
        annotations: dict[int, dict],
        categories: dict[int, dict],
        mask_cache: PolygonMaskCache,
) -> dict:
    output = _source_output(output_root, source)
    complete_path = output / "complete.json"
    per_gt_path = output / "per_gt_mask_validity.csv"
    if _run_complete_matches(complete_path, source, annotation_sha256):
        if not per_gt_path.is_file():
            raise FileNotFoundError(f"completed run is missing {per_gt_path}")
        return _read_json(output / "run_summary.json")
    output.mkdir(parents=True, exist_ok=True)
    natural_rows = _read_csv(
        _natural_source(natural_root, source) / "per_gt_collective_gain.csv"
    )
    natural_lookup = {
        (str(row["image_id"]), str(row["gt_id"])): row for row in natural_rows
    }
    if len(natural_lookup) != len(natural_rows):
        raise ValueError(f"duplicate first-round GT rows: {source.model}/seed{source.seed}")
    document = _read_json(source.prediction_file)
    metadata = document.get("metadata", {})
    if metadata.get("run_fingerprint") != source.run_fingerprint:
        raise ValueError(f"prediction metadata mismatch: {source.prediction_file}")
    class_names = metadata.get("class_names")
    if not isinstance(class_names, list) or len(class_names) != 80:
        raise ValueError(f"invalid MS COCO class-name map: {source.prediction_file}")
    results = []
    for image_record in document["images"]:
        image_id = str(image_record["image_id"])
        image_width = int(image_record["width"])
        image_height = int(image_record["height"])
        predictions_by_class = defaultdict(list)
        for prediction in image_record["predictions"]:
            if float(prediction["score"]) >= PRIMARY_THETA:
                predictions_by_class[int(prediction["class_id"])].append(prediction)
        for gt in image_record["gts"]:
            gt_id = str(gt["id"])
            key = (image_id, gt_id)
            natural = natural_lookup.pop(key, None)
            if natural is None:
                raise ValueError(f"first-round result missed {image_id}/{gt_id}")
            annotation_id = _annotation_id(gt_id)
            annotation = annotations.get(annotation_id)
            if annotation is None:
                raise ValueError(f"COCO annotation not found: {annotation_id}")
            category = categories[int(annotation["category_id"])]
            cached_class_id = int(gt["class_id"])
            if str(category["name"]) != str(class_names[cached_class_id]):
                raise ValueError(
                    f"category mismatch for annotation {annotation_id}: "
                    f"COCO={category['name']}, cache={class_names[cached_class_id]}"
                )
            image_meta = images[int(annotation["image_id"])]
            if int(image_meta["width"]) != image_width or int(image_meta["height"]) != image_height:
                raise ValueError(f"image dimensions changed for annotation {annotation_id}")
            mask_record = mask_cache.get(annotation_id)
            gt_rect = tuple(map(float, gt["xyxy"]))
            candidates = [
                prediction
                for prediction in predictions_by_class[int(gt["class_id"])]
                if _rectangle_intersects(gt_rect, prediction["xyxy"])
            ]
            foreground = foreground_metrics(
                mask_record,
                candidates,
                image_width=image_width,
                image_height=image_height,
            )
            coco_area = float(annotation["area"])
            results.append({
                "image_id": image_id,
                "gt_id": gt_id,
                "annotation_id": annotation_id,
                "class_id": int(gt["class_id"]),
                "image_file": str(image_meta["file_name"]),
                "AC": float(natural["AC"]),
                "BestIoGT": float(natural["BestIoGT"]),
                "CollectiveGain": float(natural["CollectiveGain"]),
                "ABO": float(natural["ABO"]),
                "local_VC": float(natural["local_VC"]),
                "assigned_pred_count": int(float(natural["assigned_pred_count"])),
                "box_marginal_contributor_count": int(
                    float(natural["marginal_contributor_count"])
                ),
                "box_marginal_pred_ids": str(natural["marginal_pred_ids"]),
                "box_best_pred_id": str(natural["best_pred_id"]),
                "foreground_pixel_area": mask_record.foreground_area,
                "coco_annotation_area": coco_area,
                "raster_to_coco_area_ratio": (
                    mask_record.foreground_area / coco_area if coco_area else 0.0
                ),
                **foreground,
            })
    if natural_lookup:
        raise ValueError(
            f"first-round result has {len(natural_lookup)} unmatched rows for "
            f"{source.model}/seed{source.seed}"
        )
    summary = {
        "dataset": "mscoco",
        "model": source.model,
        "seed": source.seed,
        "model_id": source.model_id,
        "source_run_fingerprint": source.run_fingerprint,
        **summarize_rows(results),
    }
    _atomic_csv(per_gt_path, results)
    _atomic_json(output / "run_summary.json", summary)
    _atomic_json(
        complete_path,
        {
            "status": "complete",
            "validity_version": VALIDITY_VERSION,
            "natural_analysis_version": NATURAL_ANALYSIS_VERSION,
            "source_run_fingerprint": source.run_fingerprint,
            "annotation_sha256": annotation_sha256,
            "theta": PRIMARY_THETA,
            "n_gt": len(results),
            "completed_at": datetime.now(timezone.utc).isoformat(),
        },
    )
    del document, natural_rows, results
    gc.collect()
    return summary


def _aggregate_five_seeds(rows: list[dict]) -> list[dict]:
    groups = defaultdict(list)
    for row in rows:
        groups[row["model"]].append(row)
    output = []
    for model in YOLO_MODELS:
        group = groups[model]
        if len(group) != 5 or {int(row["seed"]) for row in group} != set(range(5)):
            raise ValueError(f"incomplete five-seed group: {model}")
        aggregate = {"dataset": "mscoco", "model": model, "n_seeds": 5}
        excluded = {
            "dataset", "model", "seed", "model_id", "source_run_fingerprint"
        }
        for field in group[0]:
            if field in excluded:
                continue
            values = [float(row[field]) for row in group]
            aggregate[f"{field}_mean"] = statistics.fmean(values)
            aggregate[f"{field}_std"] = statistics.stdev(values)
        output.append(aggregate)
    return output


def _relationship_histograms(output: Path, sources: list[CachedRun]):
    histograms = {
        model: {
            "AC": np.zeros((60, 60), dtype=np.int64),
            "gain": np.zeros((60, 60), dtype=np.int64),
        }
        for model in YOLO_MODELS
    }
    case_rows = []
    for source in sources:
        path = _source_output(output, source) / "per_gt_mask_validity.csv"
        rows = _read_csv(path)
        box_ac = np.asarray([float(row["AC"]) for row in rows])
        mask_ac = np.asarray([float(row["MaskAC"]) for row in rows])
        box_gain = np.clip(
            np.asarray([float(row["CollectiveGain"]) for row in rows]),
            0.0, GAIN_PLOT_MAX - 1e-10,
        )
        mask_gain = np.clip(
            np.asarray([float(row["MaskCollectiveGain"]) for row in rows]),
            0.0, GAIN_PLOT_MAX - 1e-10,
        )
        histograms[source.model]["AC"] += np.histogram2d(
            box_ac, mask_ac, bins=(AC_BINS, AC_BINS)
        )[0].astype(np.int64)
        histograms[source.model]["gain"] += np.histogram2d(
            box_gain, mask_gain, bins=(GAIN_BINS, GAIN_BINS)
        )[0].astype(np.int64)
        if source.model == "yolo11s" and source.seed == 0:
            case_rows = rows
    return histograms, case_rows


def _plot_relationships(histograms: dict, output: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LogNorm

    figure, axes = plt.subplots(
        2, 3, figsize=(14.2, 8.9), constrained_layout=True
    )
    for column, model in enumerate(YOLO_MODELS):
        for row_index, (field, bins, maximum, x_label, y_label) in enumerate((
            ("AC", AC_BINS, 1.0, "Box AC", "Foreground MaskAC"),
            (
                "gain", GAIN_BINS, GAIN_PLOT_MAX,
                "Box collective gain", "Foreground collective gain",
            ),
        )):
            axis = axes[row_index, column]
            counts = histograms[model][field].T
            masked = np.ma.masked_where(counts <= 0, counts)
            positive = counts[counts > 0]
            upper = max(1.0, float(np.max(positive)) if len(positive) else 1.0)
            image = axis.imshow(
                masked,
                origin="lower",
                extent=(0, maximum, 0, maximum),
                aspect="equal",
                cmap="viridis",
                norm=LogNorm(vmin=1, vmax=upper),
            )
            axis.plot([0, maximum], [0, maximum], "--", color="white", linewidth=1.2)
            axis.set(
                title=MODEL_LABELS[model],
                xlabel=x_label,
                ylabel=y_label if column == 0 else "",
                xlim=(0, maximum),
                ylim=(0, maximum),
            )
            axis.grid(False)
            figure.colorbar(image, ax=axis, fraction=0.046, pad=0.03)
    figure.suptitle(
        "Box-level coverage versus COCO foreground-mask coverage\n"
        "(pooled observations from five training seeds)",
        fontsize=14,
    )
    figure.savefig(output / "box_vs_mask_relationships.pdf", bbox_inches="tight")
    figure.savefig(
        output / "box_vs_mask_relationships.png", dpi=240, bbox_inches="tight"
    )
    plt.close(figure)



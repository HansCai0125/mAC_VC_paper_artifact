@dataclass(frozen=True)
class PackedForegroundMask:
    """A compact local binary mask stored relative to its crop origin."""

    x0: int
    y0: int
    width: int
    height: int
    packed: np.ndarray
    foreground_area: int
    coco_area: float

    def unpack(self) -> np.ndarray:
        pixels = np.unpackbits(self.packed, count=self.width * self.height)
        return pixels.reshape(self.height, self.width).astype(bool, copy=False)


class PolygonMaskCache:
    """Lazily rasterize COCO polygons once and reuse them across 15 runs."""

    def __init__(self, annotations: dict[int, dict], images: dict[int, dict]):
        self.annotations = annotations
        self.images = images
        self._cache: dict[int, PackedForegroundMask] = {}

    def get(self, annotation_id: int) -> PackedForegroundMask:
        cached = self._cache.get(annotation_id)
        if cached is not None:
            return cached
        annotation = self.annotations[annotation_id]
        image = self.images[int(annotation["image_id"])]
        mask = rasterize_coco_polygon(annotation, image)
        self._cache[annotation_id] = mask
        return mask

    @property
    def packed_bytes(self) -> int:
        return sum(mask.packed.nbytes for mask in self._cache.values())

    @property
    def size(self) -> int:
        return len(self._cache)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _annotation_id(gt_id: str) -> int:
    value = str(gt_id)
    if value.startswith("gt_"):
        value = value[3:]
    return int(value)


def _load_coco(path: Path = ANNOTATION_FILE):
    document = _read_json(path)
    images = {int(row["id"]): row for row in document["images"]}
    annotations = {int(row["id"]): row for row in document["annotations"]}
    categories = {int(row["id"]): row for row in document["categories"]}
    return images, annotations, categories


def _mscoco_sources() -> list[CachedRun]:
    sources = [row for row in paired_yolo_sources() if row.dataset == "mscoco"]
    expected = {
        (model, seed) for model in YOLO_MODELS for seed in range(5)
    }
    actual = {(row.model, row.seed) for row in sources}
    if len(sources) != 15 or actual != expected:
        raise ValueError(
            f"MS COCO mask analysis requires 3 models x 5 seeds; got {sorted(actual)}"
        )
    return sorted(sources, key=lambda row: (MODEL_ORDER.index(row.model), row.seed))



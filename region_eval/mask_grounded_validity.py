"""Mask-grounded validation of box-level area coverage on MS COCO.

The analysis reuses the 15 completed MS COCO prediction caches
(three YOLO architectures x five training seeds).  COCO instance polygons are
used as an independent foreground reference.  No model training or inference
is performed.

For a ground-truth foreground mask M and retained same-class prediction boxes
P(theta), the primary mask-grounded quantities are

    MaskAC = |M intersect union(P)| / |M|
    MaskBest = max_p |M intersect p| / |M|
    MaskCollectiveGain = MaskAC - MaskBest.

They are paired with the box-level AC, BestIoGT, and CollectiveGain values
generated by ``natural_collective_gain.py`` for the same GT instance.
"""


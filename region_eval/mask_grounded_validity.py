def preflight_mask_grounded_validity(
        output=DEFAULT_OUTPUT,
        natural_output=NATURAL_OUTPUT,
        annotation_file=ANNOTATION_FILE,
) -> dict:
    output = Path(output).resolve()
    natural_output = Path(natural_output).resolve()
    annotation_file = Path(annotation_file).resolve()
    if not annotation_file.is_file():
        raise FileNotFoundError(f"COCO instance annotations not found: {annotation_file}")
    if not IMAGE_ROOT.is_dir():
        raise FileNotFoundError(f"COCO validation images not found: {IMAGE_ROOT}")
    natural_complete = natural_output / "analysis_complete.json"
    if not natural_complete.is_file():
        raise FileNotFoundError(
            "first-round natural analysis is missing; run "
            "experiments/collective_gain.py first"
        )
    marker = _read_json(natural_complete)
    if (
        marker.get("status") != "complete"
        or marker.get("analysis_version") != NATURAL_ANALYSIS_VERSION
    ):
        raise ValueError("first-round natural analysis is incomplete or changed")
    sources = _mscoco_sources()
    images, annotations, categories = _load_coco(annotation_file)
    first_rows = _read_csv(
        _natural_source(natural_output, sources[0]) / "per_gt_collective_gain.csv"
    )
    missing = []
    non_polygon = []
    crowd = []
    for row in first_rows:
        annotation_id = _annotation_id(row["gt_id"])
        annotation = annotations.get(annotation_id)
        if annotation is None:
            missing.append(annotation_id)
            continue
        if not isinstance(annotation.get("segmentation"), list):
            non_polygon.append(annotation_id)
        if int(annotation.get("iscrowd", 0)):
            crowd.append(annotation_id)
    if missing or non_polygon or crowd:
        raise ValueError(
            "COCO mask preflight failed: "
            f"missing={len(missing)}, non_polygon={len(non_polygon)}, crowd={len(crowd)}"
        )
    for source in sources:
        natural_run = _natural_source(natural_output, source)
        for path in (
            natural_run / "per_gt_collective_gain.csv",
            natural_run / "complete.json",
            source.prediction_file,
        ):
            if not path.is_file():
                raise FileNotFoundError(f"required input missing: {path}")
    return {
        "status": "passed",
        "validity_version": VALIDITY_VERSION,
        "natural_analysis_version": NATURAL_ANALYSIS_VERSION,
        "vc_version": VC_VERSION,
        "theta": PRIMARY_THETA,
        "n_runs": len(sources),
        "n_models": len(YOLO_MODELS),
        "n_seeds_per_model": 5,
        "n_gt_per_run": len(first_rows),
        "n_coco_annotations": len(annotations),
        "n_coco_categories": len(categories),
        "selected_annotation_encoding": "polygon",
        "selected_crowd_annotations": len(crowd),
        "mask_rasterizer": "OpenCV local-crop polygon rasterization",
        "annotation_file": str(annotation_file),
        "annotation_sha256": _sha256(annotation_file),
        "estimated_packed_mask_bytes": sum(
            int(ceil(float(annotations[_annotation_id(row['gt_id'])]['bbox'][2])))
            * int(ceil(float(annotations[_annotation_id(row['gt_id'])]['bbox'][3])))
            for row in first_rows
        ) // 8,
        "output": str(output),
        "training": False,
        "inference": False,
    }


def run_mask_grounded_validity(
        output=DEFAULT_OUTPUT,
        natural_output=NATURAL_OUTPUT,
        annotation_file=ANNOTATION_FILE,
) -> Path:
    output = Path(output).resolve()
    natural_output = Path(natural_output).resolve()
    annotation_file = Path(annotation_file).resolve()
    output.mkdir(parents=True, exist_ok=True)
    preflight = preflight_mask_grounded_validity(
        output=output,
        natural_output=natural_output,
        annotation_file=annotation_file,
    )
    _atomic_json(output / "preflight.json", preflight)
    annotation_sha256 = str(preflight["annotation_sha256"])
    images, annotations, categories = _load_coco(annotation_file)
    mask_cache = PolygonMaskCache(annotations, images)
    sources = _mscoco_sources()
    run_rows = []
    for index, source in enumerate(sources, 1):
        print(
            f"MASK-VALIDITY {index:02d}/{len(sources):02d} START: "
            f"mscoco:{source.model}:seed{source.seed}",
            flush=True,
        )
        summary = _evaluate_source(
            source,
            output_root=output,
            natural_root=natural_output,
            annotation_sha256=annotation_sha256,
            images=images,
            annotations=annotations,
            categories=categories,
            mask_cache=mask_cache,
        )
        run_rows.append(summary)
        print(
            f"MASK-VALIDITY {index:02d}/{len(sources):02d} COMPLETE: "
            f"mscoco:{source.model}:seed{source.seed}; "
            f"mask_cache={mask_cache.size} GT, "
            f"{mask_cache.packed_bytes / (1024**2):.1f} MiB",
            flush=True,
        )
    model_rows = _aggregate_five_seeds(run_rows)
    _atomic_csv(output / "run_summary.csv", run_rows)
    _atomic_csv(output / "model_summary.csv", model_rows)
    histograms, case_rows = _relationship_histograms(output, sources)
    _plot_relationships(histograms, output)
    _plot_validity_rates(model_rows, output)
    case_source = next(
        source for source in sources if source.model == "yolo11s" and source.seed == 0
    )
    _plot_cases(
        case_rows, case_source, annotations, images, mask_cache, output
    )
    _latex_table(model_rows, output)
    _report(model_rows, output)
    complete = {
        "status": "complete",
        "validity_version": VALIDITY_VERSION,
        "natural_analysis_version": NATURAL_ANALYSIS_VERSION,
        "vc_version": VC_VERSION,
        "theta": PRIMARY_THETA,
        "annotation_sha256": annotation_sha256,
        "n_runs": len(run_rows),
        "n_models": len(model_rows),
        "n_seeds_per_model": 5,
        "mask_cache_count": mask_cache.size,
        "mask_cache_packed_bytes": mask_cache.packed_bytes,
        "training": False,
        "inference": False,
        "completed_at": datetime.now(timezone.utc).isoformat(),
        "output": str(output),
    }
    _atomic_json(output / "analysis_complete.json", complete)
    return output

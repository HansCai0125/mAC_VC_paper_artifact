def _select_cases(rows: list[dict]) -> list[dict]:
    """Select four distinct, auditable cases without assuming an outcome."""
    candidates = [dict(row) for row in rows]
    selected = []
    used = set()

    def take(label, score, predicate=lambda row: True):
        ordered = sorted(
            (row for row in candidates if predicate(row)),
            key=lambda row: (
                -score(row), str(row["image_id"]), str(row["gt_id"])
            ),
        )
        for row in ordered:
            key = (row["image_id"], row["gt_id"])
            if key not in used:
                row["case_type"] = label
                selected.append(row)
                used.add(key)
                return
        raise ValueError(f"unable to select qualitative case: {label}")

    take(
        "Foreground-confirmed collective coverage",
        lambda row: min(float(row["CollectiveGain"]), float(row["MaskCollectiveGain"])),
        lambda row: (
            float(row["CollectiveGain"]) > GAIN_THRESHOLD
            and float(row["MaskCollectiveGain"]) > GAIN_THRESHOLD
            and float(row["local_VC"]) >= 0.50
        ),
    )
    take(
        "Box collective gain exceeds foreground gain",
        lambda row: float(row["CollectiveGain"]) - float(row["MaskCollectiveGain"]),
        lambda row: float(row["CollectiveGain"]) > GAIN_THRESHOLD,
    )
    take(
        "Box AC exceeds foreground coverage",
        lambda row: float(row["AC"]) - float(row["MaskAC"]),
    )
    take(
        "Foreground coverage exceeds box AC",
        lambda row: float(row["MaskAC"]) - float(row["AC"]),
    )
    return selected


def _prediction_ids(row: dict) -> set[str]:
    values = set()
    for field in (
        "box_marginal_pred_ids", "mask_marginal_pred_ids",
        "box_best_pred_id", "mask_best_pred_id",
    ):
        values.update(value for value in str(row.get(field, "")).split(";") if value)
    return values


def _plot_cases(
        rows: list[dict],
        source: CachedRun,
        annotations: dict[int, dict],
        images: dict[int, dict],
        mask_cache: PolygonMaskCache,
        output: Path,
) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch, Rectangle
    from PIL import Image

    selected = _select_cases(rows)
    document = _read_json(source.prediction_file)
    image_lookup = {str(row["image_id"]): row for row in document["images"]}
    figure, axes = plt.subplots(2, 2, figsize=(13.4, 10.2))
    manifest = []
    for axis, row in zip(axes.flat, selected):
        image_record = image_lookup[str(row["image_id"])]
        gt = next(
            value for value in image_record["gts"]
            if str(value["id"]) == str(row["gt_id"])
        )
        annotation_id = int(row["annotation_id"])
        annotation = annotations[annotation_id]
        image_meta = images[int(annotation["image_id"])]
        image_path = IMAGE_ROOT / str(image_meta["file_name"])
        predictions = {
            str(value["id"]): value for value in image_record["predictions"]
        }
        relevant = [
            predictions[value] for value in _prediction_ids(row)
            if value in predictions
        ]
        with Image.open(image_path) as source_image:
            axis.imshow(source_image.convert("RGB"))
        mask_record = mask_cache.get(annotation_id)
        local_mask = mask_record.unpack()
        overlay = np.ma.masked_where(~local_mask, local_mask)
        axis.imshow(
            overlay,
            cmap="Reds",
            alpha=0.28,
            interpolation="nearest",
            extent=(
                mask_record.x0,
                mask_record.x0 + mask_record.width,
                mask_record.y0 + mask_record.height,
                mask_record.y0,
            ),
        )
        box_marginal = {
            value for value in str(row["box_marginal_pred_ids"]).split(";") if value
        }
        mask_marginal = {
            value for value in str(row["mask_marginal_pred_ids"]).split(";") if value
        }
        for prediction in relevant:
            px1, py1, px2, py2 = map(float, prediction["xyxy"])
            pred_id = str(prediction["id"])
            if pred_id in box_marginal and pred_id in mask_marginal:
                color, linewidth = "#2ca02c", 2.2
            elif pred_id in mask_marginal:
                color, linewidth = "#ff7f0e", 1.8
            else:
                color, linewidth = "#1f77b4", 1.5
            axis.add_patch(Rectangle(
                (px1, py1), px2 - px1, py2 - py1,
                fill=False, edgecolor=color, linewidth=linewidth,
            ))
        gx1, gy1, gx2, gy2 = map(float, gt["xyxy"])
        axis.add_patch(Rectangle(
            (gx1, gy1), gx2 - gx1, gy2 - gy1,
            fill=False, edgecolor="#d62728", linewidth=2.5,
        ))
        coordinates = [(gx1, gy1, gx2, gy2)] + [
            tuple(map(float, value["xyxy"])) for value in relevant
        ]
        x1 = min(value[0] for value in coordinates)
        y1 = min(value[1] for value in coordinates)
        x2 = max(value[2] for value in coordinates)
        y2 = max(value[3] for value in coordinates)
        margin = 0.20 * max(x2 - x1, y2 - y1, 20.0)
        axis.set_xlim(max(0, x1 - margin), min(int(image_record["width"]), x2 + margin))
        axis.set_ylim(min(int(image_record["height"]), y2 + margin), max(0, y1 - margin))
        axis.set_title(
            f"{row['case_type']}\n"
            f"Box AC={float(row['AC']):.2f}, MaskAC={float(row['MaskAC']):.2f}; "
            f"Box $\\Delta$={float(row['CollectiveGain']):.2f}, "
            f"Mask $\\Delta$={float(row['MaskCollectiveGain']):.2f}; "
            f"VC={float(row['local_VC']):.2f}",
            fontsize=10,
        )
        axis.axis("off")
        manifest.append({
            "case_type": row["case_type"],
            "model": source.model,
            "seed": source.seed,
            "image_id": row["image_id"],
            "gt_id": row["gt_id"],
            "annotation_id": annotation_id,
            "class_id": row["class_id"],
            "AC": row["AC"],
            "MaskAC": row["MaskAC"],
            "CollectiveGain": row["CollectiveGain"],
            "MaskCollectiveGain": row["MaskCollectiveGain"],
            "VC": row["local_VC"],
            "image_path": str(image_path),
        })
    figure.legend(
        handles=[
            Patch(facecolor="#d62728", alpha=0.28, label="COCO foreground mask"),
            Patch(facecolor="none", edgecolor="#d62728", label="GT box"),
            Patch(facecolor="none", edgecolor="#2ca02c", label="Box and mask contributor"),
            Patch(facecolor="none", edgecolor="#ff7f0e", label="Mask contributor"),
            Patch(facecolor="none", edgecolor="#1f77b4", label="Other selected box"),
        ],
        loc="upper center",
        ncol=3,
        frameon=False,
    )
    figure.tight_layout(rect=(0, 0, 1, 0.93))
    figure.savefig(output / "mask_grounded_cases.pdf", bbox_inches="tight")
    figure.savefig(output / "mask_grounded_cases.png", dpi=240, bbox_inches="tight")
    plt.close(figure)
    _atomic_csv(output / "qualitative_case_manifest.csv", manifest)


